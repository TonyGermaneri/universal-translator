#!/usr/bin/env python3
"""Pins the SHA-256 of every downloadable model file, so downloads and manual imports can be verified.

Reads each `LocalModel(...)` in Sources/UniversalTranslator/Translation/LocalModels.swift (id, repository, revision,
remoteFolder, and `files` when it's a literal list), asks the Hugging Face API for the files at that revision (LFS
files come with their SHA-256; small files are fetched and hashed), and writes
Sources/UniversalTranslator/Translation/ModelHashes.swift. Rerun it whenever a model's revision changes.

usage: scripts/pin-model-hashes.py
A model whose revision isn't a commit ("main") is refused: a hash pinned to a moving branch breaks on its next push.
"""
import hashlib
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOG = os.path.join(ROOT, "Sources", "UniversalTranslator", "Translation", "LocalModels.swift")
OUT = os.path.join(ROOT, "Sources", "UniversalTranslator", "Translation", "ModelHashes.swift")


def fetch(url):
    # curl, not urllib: it uses the system's trust store the same way everywhere.
    return subprocess.run(["curl", "-sfL", url], check=True, capture_output=True).stdout


def models():
    source = open(CATALOG, encoding="utf-8").read()
    for block in re.findall(r"LocalModel\((.*?)\n    \)", source, re.S):
        field = lambda name: (re.search(name + r':\s*"([^"]*)"', block) or [None, None])[1]
        files = re.search(r'files:\s*\[([^\]]*)\]', block)
        listed = re.findall(r'"([^"]+)"', files.group(1)) if files else None
        yield {"id": field("id"), "repo": field("repository"), "revision": field("revision") or "main",
               "folder": field("remoteFolder") or "", "files": listed}


def main():
    pinned = {}
    for m in models():
        if not re.fullmatch(r"[0-9a-f]{40}", m["revision"]):
            sys.exit(f"{m['id']}: revision '{m['revision']}' isn't a commit; pin it in LocalModels.swift first")
        url = f"https://huggingface.co/api/models/{m['repo']}/tree/{m['revision']}"
        url += (f"/{m['folder']}" if m["folder"] else "") + "?recursive=true"
        prefix = m["folder"] + "/" if m["folder"] else ""
        hashes = {}
        for entry in json.loads(fetch(url)):
            if entry["type"] != "file":
                continue
            path = entry["path"][len(prefix):]
            if m["files"] is not None and path not in m["files"]:
                continue
            if entry.get("lfs"):
                hashes[path] = entry["lfs"]["oid"]
            else:
                data = fetch(f"https://huggingface.co/{m['repo']}/resolve/{m['revision']}/{prefix}{path}")
                hashes[path] = hashlib.sha256(data).hexdigest()
        pinned[m["id"]] = dict(sorted(hashes.items()))
        print(f"{m['id']}: {len(hashes)} files")

    lines = ["// Generated by scripts/pin-model-hashes.py from Hugging Face at each model's pinned revision. Don't edit;",
             "// rerun the script when a revision in LocalModels.swift changes.",
             "extension LocalModel {",
             "    /// SHA-256 of each file, by model id and the file's path within the model.",
             "    static let pinnedSHA256: [String: [String: String]] = ["]
    for model_id, hashes in pinned.items():
        lines.append(f'        "{model_id}": [')
        lines += [f'            "{path}": "{digest}",' for path, digest in hashes.items()]
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    open(OUT, "w", encoding="utf-8").write("\n".join(lines))
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
